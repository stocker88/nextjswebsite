const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
const {buildTrades}=require('./build-mover-trades.cjs');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,f);
const {findMoverTrade}=require('../lib/mover-trades.ts');
const now=Date.parse('2026-10-24T00:00:00Z');
const result={id:'options_results_ACN_2026-10-23',symbol:'ACN',sessionDay:'2026-10-23',title:'ACN call results'};
const post={id:result.id,symbols:['acn','options','results'],time:now/1000-3600};
const items=buildTrades([result],[post],now);
assert.equal(items.length,1);assert.equal(items[0].isAIAdvisor,true);assert.equal(items[0].postId,post.id);
assert.equal(items[0].href,'/results/options-results-acn-2026-10-23/');
assert.equal(findMoverTrade(items,'ACN',now).postId,post.id);assert.equal(findMoverTrade(items,'AC',now),undefined);
assert.equal(buildTrades([result],[{...post,id:'another-post'}],now).length,0);
assert.equal(buildTrades([result],[{...post,isAIAdvisor:false}],now).length,0);
assert.equal(buildTrades([result],[{...post,symbols:['PANW']}],now).length,0);
for(const time of [now/1000+1,(now-7*86400000-1)/1000,null])assert.equal(buildTrades([result],[{...post,time}],now).length,0);
assert.equal(buildTrades([{...result,sessionDay:'2026-10-01'}],[post],now).length,0);
for(const change of [{isAIAdvisor:false},{href:'//evil.example/'},{publishedAt:new Date(now+1).toISOString()},{publishedAt:new Date(now-7*86400000-1).toISOString()}])assert.equal(findMoverTrade([{...items[0],...change}],'ACN',now),undefined);
assert.equal(findMoverTrade([{...items[0],symbol:'BRK.B'}],'BRK-B',now).symbol,'BRK.B');
assert.equal(findMoverTrade([items[0],{...items[0],postId:'newer',publishedAt:new Date(now-1).toISOString()}],'ACN',now).postId,'newer');
console.log('PASS: recent AI-only result-post joins, exact tickers, original IDs, canonical detail links, expiry, future dates and newest-result selection.');
