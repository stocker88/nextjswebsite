const assert=require('node:assert/strict'),fs=require('node:fs'),ts=require('typescript');
require.extensions['.ts']=(m,f)=>m._compile(ts.transpileModule(fs.readFileSync(f,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS}}).outputText,f);
const {portfolioDataCsv,portfolioDataFilename,portfolioDataText}=require('../lib/portfolio-data-export.ts');
const rows=Array.from({length:31},(_,i)=>({symbol:`TEST${i}`,value:i,weight:null,company:'Example, "Inc"'}));
const data={name:'Example Investor',kind:'funds',disclosure:'Reported holdings, not live positions.'};
const csv=portfolioDataCsv(data,rows,'2026-06-30');
assert.ok(csv.startsWith('\uFEFF'));
assert.equal(csv.split('\r\n').length,33);
assert.ok(csv.includes('"TEST30"')); // Not capped at the image top 10 or visible first 20.
assert.ok(csv.includes('"Example, ""Inc"""'));
assert.ok(csv.includes('"0","",""')); // Zero value preserved; missing shares/weight blank.
assert.ok(csv.includes('"2026-06-30"'));
const political=portfolioDataCsv({...data,kind:'politicians'},[{symbol:'ABC',amount:'$1,001–$15,000',rawAction:'Purchase',company:'=HYPERLINK("evil")'}],'');
assert.ok(political.includes('"$1,001–$15,000"'));
assert.ok(political.includes('"\'=HYPERLINK'));
assert.equal(portfolioDataFilename('../test',''), 'investor-tracker-..-test-all-disclosures.csv');
console.log('PASS CSV full rows, periods, ranges, zero/missing values, escaping and formula protection.');
const text=portfolioDataText(data,rows,'2026-06-30');
assert.equal(text.split('\n').filter(line=>line.startsWith('$TEST')).length,31);
assert.ok(text.includes('Quarter ending 2026-06-30'));
assert.ok(text.includes('$TEST0 · Example, "Inc" · $0 · Weight not disclosed'));
assert.ok(text.endsWith('Source: StocksToBuyNow.ai'));
const holding=portfolioDataText(data,[{symbol:'$AAPL',company:'APPLE\nINC',value:66000000000,weight:22}],'');
assert.ok(holding.includes('$AAPL · APPLE INC · $66B · 22.0%'));
assert.ok(!holding.includes('Quarter ending'));
const transaction=portfolioDataText({...data,kind:'politicians'},[{symbol:'XYZ',amount:'$1,001–$15,000',rawAction:'Purchase',weight:0}],'2026-10');
assert.ok(transaction.includes('Filed in 2026-10'));
assert.ok(transaction.includes('$1,001–$15,000 · 0.0% · Purchase'));
assert.ok(portfolioDataText(data,[{symbol:'XYZ',value:NaN,weight:Infinity}],'').includes('Value not disclosed · Weight not disclosed'));
console.log('PASS app-matching copy format, full selected rows, missing/zero values, ranges, actions and source.');
